export function loadDatabase(): SiakDatabase {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(DB_PATH)) {
    const initial = buildInitialDatabase();
    fs.writeFileSync(DB_PATH, JSON.stringify(initial, null, 2), 'utf8');
    return initial;
  }
  const raw = fs.readFileSync(DB_PATH, 'utf8');
  return JSON.parse(raw) as SiakDatabase;
}

export function saveDatabase(db: SiakDatabase): void {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  fs.writeFileSync(DB_PATH, JSON.stringify(db, null, 2), 'utf8');
}

export function sanitizeUser(user: UserRecord, db: SiakDatabase): SafeUser {
  const rw = user.rw_id ? db.rws.find((r) => r.id === user.rw_id) : undefined;
  const rt = user.rt_id ? db.rts.find((r) => r.id === user.rt_id) : undefined;
  return {
    id: user.id,
    name: user.name,
    email: user.email,
    role: user.role,
    rw_id: user.rw_id,
    rt_id: user.rt_id,
    active: user.active,
    created_at: user.created_at,
    rw_label: rw ? `RW ${rw.nomor_rw}` : undefined,
    rt_label: rt ? `RT ${rt.nomor_rt}` : undefined,
  };
}
